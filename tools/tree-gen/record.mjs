#!/usr/bin/env node
/**
 * Account for the generated hero-tree GLBs in the model ledger and the model-file table:
 *
 *   node tools/tree-gen/build.mjs && node tools/tree-gen/record.mjs
 *
 * The files are original procedural work (tools/tree-gen: generated geometry, generated bark and a generated placeholder
 * leaf atlas; no third-party model, image or Meshy output), so they are recorded under their own source, not a Meshy one.
 */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeLedger } from '../model-ledger/meshy.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const ledgerPath = path.join(root, 'public/model-licenses.json');
const ledger = JSON.parse(fs.readFileSync(ledgerPath, 'utf8'));
const SOURCE_ID = 'tervain-hero-oak';
const dir = 'public/models/flora/hero';
const files = fs.readdirSync(path.join(root, dir)).filter((f) => f.endsWith('.glb')).sort();

ledger.sources[SOURCE_ID] = {
  filename: 'tools/tree-gen (procedural generator, no input files)',
  sha256: null,
  sourceRecord: 'tools/tree-gen/build.mjs',
  sourceAssetUrl: null,
  recordedSupplier: 'Tervain project',
  creator: 'Tervain project (generated by tools/tree-gen)',
  generationService: 'Tervain procedural generator',
  license: {
    spdx: null,
    version: null,
    evidenceStatus: 'tervain-original-procedural',
    creator: 'Tervain project',
    terms: 'Original work of the Tervain project. Geometry, bark textures and the placeholder leaf atlas are computed by tools/tree-gen from seeded noise and algorithms written for Tervain; no third-party model, image, scan or Meshy output is an input. Rights are reserved by the project owner; LICENSE-SCOPE.md grants nothing for 3D models.',
  },
  credit: 'Hero oaks and birches: grown and textured procedurally by Tervain (tools/tree-gen).',
  changes: 'Generated at build time by tools/tree-gen/build.mjs (seeded; four-level branch skeleton, bark-relief tubes, buttress roots, leaf cards). Not derived from any other model.',
  rightsBoundary: 'Original Tervain procedural output. No Meshy, Community or third-party rights are involved.',
  provenance: { classification: 'tervain-original-procedural', evidence: 'The files are the deterministic output of tools/tree-gen/build.mjs (seed recorded in each file’s asset.extras); the generator and every texture it writes are original code in this repository.', creator: 'Tervain project', listingUrl: null },
};

let added = 0;
for (const name of files) {
  const file = `${dir}/${name}`, bytes = fs.readFileSync(path.join(root, file));
  const entry = {
    file, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex'),
    embeddedCopyright: null, embeddedCcDeclaration: false, externalDependencies: [],
    scope: 'original-game-model-catalog', sourceId: SOURCE_ID,
    license: { spdx: null, version: null, evidenceStatus: 'tervain-original-procedural', creator: 'Tervain project' },
    modified: false,
  };
  const previous = ledger.assets.find((a) => a.file === file);
  ledger.assets = ledger.assets.filter((a) => a.file !== file);
  ledger.assets.push(entry);
  ledger.summary.publicModelBytes += entry.bytes - (previous?.bytes ?? 0);
  if (!previous) { ledger.summary.publicModelFiles++; ledger.summary.hashesMatchedExistingSourceRecords++; added++; }
}
ledger.assets.sort((a, b) => (a.file < b.file ? -1 : a.file > b.file ? 1 : 0));
fs.writeFileSync(ledgerPath, JSON.stringify(ledger, null, 2) + '\n');
execFileSync(process.execPath, [path.join(root, 'tools/model-files.mjs')], { stdio: 'inherit', cwd: root });
console.log(`ledger: ${files.length} hero files recorded (${added} new), ${ledger.summary.publicModelFiles} public models`);
